package com.steliosgeox.carlauncher.ui.theme

/**
 * Visual theme modes for the car launcher dashboard.
 * Each mode defines a distinct color palette optimized for different driving contexts.
 */
enum class ThemeMode {
    /** Dark blue-tinted palette — low glare for nighttime driving */
    NIGHT,
    /** Slightly elevated contrast palette — daytime visibility */
    DAY,
    /** Red-accent palette — aggressive aesthetic for spirited driving */
    SPORT
}
